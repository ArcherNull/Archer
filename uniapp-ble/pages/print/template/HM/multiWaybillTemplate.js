/**
 * 汉印 — 多联运单模板（O097=1 或 O097=2 非托运客户联）
 * 布局对齐 CC3/multiWaybillTemplate，指令走 PrinterCpcl
 */
import { LOGO_EG_DATA } from './logo.js'
import {
	buildCpcl,
	createGetVal,
	page,
	raw,
	prefeed,
	alignCenter,
	alignRight,
	alignLeft,
	logoEg,
	setBold,
	setMag,
	text,
	qr,
	line,
	formPrint,
} from './cpclHelper.js'

export function getMultiWaybillTemplate(wybillData, type) {
	const getVal = createGetVal(wybillData || {})
	return buildCpcl((P) => {
		page(P, 1200)
		raw(P, 'PAGE-WIDTH 575')
		prefeed(P, 10)
		alignCenter(P)
		logoEg(P, 8, 58, -235, 20, LOGO_EG_DATA)
		setBold(P, 2)
		setMag(P, 2, 2)
		text(P, 3, 0, 0, 10, '德坤浩运')
		setMag(P, 0, 0)
		setMag(P, 2)
		text(P, 7, 0, 0, 60, 'DeKun LOGISTICS')
		setMag(P, 0)
		setBold(P, 0)
		alignRight(P)

		text(P, 3, 0, 0, 80, type)
		text(P, 55, 0, 470, 145, `第${getVal('打印次数')}次打印`)
		text(P, 3, 0, 0, 205, `电话：${getVal('发货人电话')}`)
		text(P, 3, 0, 0, 235, `电话：${getVal('收货人电话')}`)
		text(P, 3, 0, 0, 305, `件数：${getVal('件数')}`)
		text(P, 3, 0, 0, 335, `回单：${getVal('回单')}`)
		text(
			P,
			3,
			0,
			0,
			365,
			`体积：${getVal(type === '托运客户联' ? '体积' : '计费体积')}`
		)
		text(P, 3, 0, 0, 435, `合计应收：${getVal('合计应收')}`)
		text(P, 3, 0, 0, 465, `交货方式：${getVal('交货方式')}`)
		if (type != '收货客户联') {
			text(P, 3, 0, 0, 1060, '扫一扫查单       ')
		} else {
			text(P, 3, 0, 0, 1135, '扫一扫查单       ')
		}

		alignLeft(P)
		text(
			P,
			3,
			0,
			0,
			110,
			`${getVal('开单网点简称')}--${getVal('中转地')}/${getVal('路由目的地')}`
		)
		text(P, 3, 0, 0, 140, `运单号：${getVal('运单号')} `)
		text(P, 3, 0, 0, 170, `运单时间：${getVal('开单日期')}`)
		text(P, 3, 0, 0, 205, `发货人：${getVal('发货人')}`)
		text(P, 3, 0, 0, 235, `收货人：${getVal('收货人')}`)
		text(P, 3, 0, 0, 265, `地址：${getVal('收货地址')}`)
		text(P, 3, 0, 0, 305, `品名：${getVal('货名')}`)
		text(P, 3, 0, 0, 335, `包装：${getVal('包装')}`)
		text(
			P,
			3,
			0,
			0,
			365,
			`重量：${getVal(type === '托运客户联' ? '重量' : '计费重量')}Kg`
		)
		text(P, 3, 0, 0, 405, getVal('付款运费'))
		text(P, 3, 0, 0, 435, `代收：${getVal('代收')}`)
		text(P, 3, 0, 0, 465, `付款方式：${getVal('付款方式')}`)
		text(P, 3, 0, 0, 500, `备注：${getVal('备注')}`)

		text(P, 55, 0, 10, 535, '托运人注意事项')
		text(P, 55, 0, 10, 555, '1.托运人不得托运易燃、易爆、易渗漏、有毒等危险货物，不得托运国家法律')
		text(P, 55, 0, 10, 575, '法规禁止运输的货物；托运人不接收和运输上述货物，若为隐报、错报，由此')
		text(P, 55, 0, 10, 595, '产生的全部责任、损失、人身伤害或财产损失均由托运人或第三方造成。')
		text(P, 55, 0, 10, 615, '2.托运人应如实告知托运货物的品名和性质，不得匿报或瞒报，因托运货物为')
		text(P, 55, 0, 10, 635, '危险品品发生爆燃、自爆等其他严重后果，均由托运人承担和赔偿。')
		text(P, 55, 0, 10, 655, '3.本运单所有内容均为承运人根据托运人申报的信息填写，托运人应当如实申')
		text(P, 55, 0, 10, 675, '报货物信息并在收到运单后查验无误，并承认对运单内容有异议的，应当立即')
		text(P, 55, 0, 10, 695, '提出；托运人对运单；托运人未提出异议的，视为确认本运单无误。')
		text(P, 55, 0, 10, 715, '4.托运人可以选择保价或者不保价运输。托运人选择不保价运输的，发生货损')
		text(P, 55, 0, 10, 735, '货差承运人最高按照运费三倍金额赔偿。托运人选择保价运输的，应当按照货')
		text(P, 55, 0, 10, 755, '物实际价值向承运人声明并支付声明价值费，托运人声明价值不得超过货物实')
		text(P, 55, 0, 10, 775, '际价值。声明价值的货物发生货损货差的，实际损失金额低于声明价值的，承')
		text(P, 55, 0, 10, 795, '运人按照实际损失金额赔偿；实际损失金额高于声明价值的，承运人按照声明')
		text(P, 55, 0, 10, 815, '价值赔偿。')
		text(P, 55, 0, 10, 835, '5.托运人同意确认，承运人可以将其托运的货物与其他货物进行集装后自行或')
		text(P, 55, 0, 10, 855, '者转委托第三方进行运输，托运人对此没有任何异议。')

		if (type != '收货客户联') {
			text(P, 3, 0, 10, 885, `打印操作员：${getVal('打印操作员')}`)
			text(P, 3, 0, 10, 915, '查货电话：400-999-2089')
			text(P, 3, 0, 10, 945, '客服电话：400-999-2089')
			if (type == '记账联' || type == '存根联') {
				text(P, 3, 0, 10, 975, '货款电话：0371-53397802')
			} else {
				text(P, 3, 0, 10, 975, `发站电话：${getVal('发站电话')}`)
				text(P, 3, 0, 10, 1005, `到站电话：${getVal('到站电话')}`)
				text(P, 3, 0, 10, 1035, '货款电话：0371-53397802')
			}
			qr(
				P,
				350,
				890,
				4,
				5,
				`http://tms.dekuncn.com:9011/#/home?customerCode=${getVal('运单号')} `
			)
			line(P, 0, 875, 820, 875, 2)
		} else {
			text(P, 55, 0, 10, 875, '6.收货客户联签名必须为发货人指定的收货人，如果收货人是自然人，需要出')
			text(P, 55, 0, 10, 895, '示身份证；如果收货人是公司，收货人需要出示授权委托书及身份证')
			text(P, 3, 0, 10, 915, '收货人签名：')
			line(P, 0, 945, 820, 945, 2)
			text(P, 3, 0, 10, 955, `打印操作员：${getVal('打印操作员')}`)
			text(P, 3, 0, 10, 985, '查货电话：400-999-2089')
			text(P, 3, 0, 10, 1015, '客服电话：400-999-2089')
			text(P, 3, 0, 10, 1045, `发站电话：${getVal('发站电话')}`)
			text(P, 3, 0, 10, 1075, `到站电话：${getVal('到站电话')}`)
			text(P, 3, 0, 10, 1105, '货款电话：0371-53397802')
			qr(
				P,
				350,
				960,
				4,
				5,
				`http://tms.dekuncn.com:9011/#/home?customerCode=${getVal('运单号')} `
			)
		}

		line(P, 0, 195, 820, 195, 2)
		line(P, 0, 295, 820, 295, 2)
		line(P, 0, 395, 820, 395, 2)
		line(P, 0, 495, 820, 495, 2)
		line(P, 0, 530, 820, 530, 2)

		formPrint(P)
	})
}
